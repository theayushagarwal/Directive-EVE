"""Write fully explicit sample configs (map, EVE, clues, decoys, first signal all spelled out)
so a reader can see exactly what each mission contains. Re-run to regenerate."""
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from walle.config import load_config  # noqa: E402
from walle.scenarios import make_config  # noqa: E402
from walle.world import World  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent


def explicit(cfg: dict) -> dict:
    w = World(cfg)
    walls = [[int(x), int(y)] for y, x in zip(*w.walls.nonzero())]
    out = {
        "name": cfg["name"],
        "seed": cfg["seed"],
        "map": {"width": w.W, "height": w.H, "walls": walls},
        "start": list(w.start),
        "stations": [list(s) for s in w.stations],
        "resources": cfg["resources"],
        "sensors": cfg["sensors"],
        "dropout": cfg["dropout"],
        "initial_signal": {k: round(v, 4) for k, v in w.initial_signal.items()},
        "hidden": {
            "eve": {"pos": list(w.eve_pos), "status": w.eve_status},
            "clues": [{"pos": list(c["pos"]), "target": list(c["target"]), "sigma": c["sigma"], "decoy": c["decoy"]}
                      for c in w.clues],
            "decoys": [list(d) for d in w.decoys],
            "clue_radius": cfg["hidden"]["clue_radius"],
            "spoof_prob": cfg["hidden"]["spoof_prob"],
        },
        "agent": cfg["agent"],
    }
    return out


def main():
    jobs = [("mission_easy", make_config(7, "clean")), ("mission_decoys", make_config(3, "decoys"))]
    for name, cfg in jobs:
        cfg = load_config({**cfg, "name": name})
        text = yaml.safe_dump(explicit(cfg), sort_keys=False, default_flow_style=None, width=100)
        path = ROOT / "configs" / f"{name}.yaml"
        path.write_text(f"# Generated by scripts/make_configs.py. Every value is explicit and editable.\n{text}")
        print("wrote", path)


if __name__ == "__main__":
    main()
